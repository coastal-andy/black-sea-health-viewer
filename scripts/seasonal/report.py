"""README writer for scripts/seasonal/run_seasonal.py (tables, figures, plain-language sentences)."""
from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import pandas as pd

UNIT = {"sst": "°C", "chl": "log10(mg/m³)", "sal": "PSU", "o2": "mg/L"}
TITLE = {"sst": "Sea surface temperature", "chl": "Chlorophyll-a (surface, log10)", "sal": "Surface salinity",
         "o2": "Surface dissolved oxygen"}
SRC = {"insitu": "buoy (in situ)", "satellite": "satellite", "model": "model"}


def _p(p) -> str:
    return "" if p is None or (isinstance(p, float) and np.isnan(p)) else ("< 0.001" if p < 0.001 else f"{p:.3f}")


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r) + " |")
    return "\n".join(out)


def _fit_rows(var: str, cyc: pd.DataFrame, mod: pd.DataFrame, nest: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, m in mod[mod.variable == var].iterrows():
        k = (cyc.station == m.station) & (cyc.variable == var) & (cyc.source == m.source) & (cyc.window == m.window)
        cs = cyc[k]
        parts = []
        for _, c in cs.iterrows():
            snap = f" (PSD {c.period_psd_d:.0f})" if c.snapped and abs(c.period_psd_d - c.period_d) > 0.5 else ""
            own = f"{c.station}/{var}/{c.source}"
            if c.period_from != own:
                st2, _, src2 = c.period_from.split("/")
                snap += f" (period from {SRC[src2]} {st2 if st2 != c.station else ''})".replace(" )", ")")
            parts.append(f"{c.period_d:.1f} d{snap}: {c.amplitude:.2f} [{c.amp_ci_lo:.2f}, {c.amp_ci_hi:.2f}], "
                         f"max {c.max_date} ± {1.96 * c.phase_se_d:.0f} d, p {_p(c.p_hac)}")
        nk = nest[(nest.station == m.station) & (nest.variable == var) & (nest.source == m.source)
                  & (nest.window == m.window)].sort_values("k")
        daic = ", ".join(f"{x:+.0f}" for x in nk.dAIC.dropna())
        rows.append({"station": m.station, "source": SRC[m.source], "window": f"{m.window} {m.start[:7]} to {m.end[:7]}",
                     "n": int(m.n), f"cycles: amplitude [95 % CI] ({UNIT[var]}), max date ± 95 %, p (HAC)":
                         "<br>".join(parts) or "no significant fittable PSD peak",
                     "adj. R²": f"{m.r2_adj:.2f}", f"resid sd ({UNIT[var]})": f"{m.resid_sd:.2f}",
                     "dAIC per added cycle": daic, "resid lag-1 r": f"{m.lag1_autocorr:.2f}",
                     "Ljung-Box p": _p(m.ljung_box_p)})
    return pd.DataFrame(rows)


def _trend_rows(var: str, trd: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, t in trd[trd.variable == var].iterrows():
        if t.meaningful:
            val = f"{t.slope_per_decade:+.2f} [{t.ci_lo:+.2f}, {t.ci_hi:+.2f}]"
            if var == "chl":
                val += f" ({(10 ** t.slope_per_decade - 1) * 100:+.0f} %/decade)"
        else:
            val = "not meaningful"
        rows.append({"station": t.station, "source": SRC[t.source], "complete years": t.years or "-",
                     "n years": int(t.n_years), f"slope ({UNIT[var]}/decade) [95 % CI]": val,
                     "p": _p(t.p_value) if t.meaningful else "", "R²": f"{t.r2:.2f}" if t.meaningful else "",
                     "note": t.note if isinstance(t.note, str) else ""})
    return pd.DataFrame(rows)


def write(out: Path, peaks, cyc, mod, nest, trd, syn, synfigs, summary) -> Path:
    L = []
    L += ["# Seasonal cycles and interannual trend", "",
          f"Romanian Black Sea shelf, offshore buoys. Generated by `scripts/seasonal/run_seasonal.py` on "
          f"{time.strftime('%Y-%m-%d %H:%M')} from cached data only (`MARINEKIT_OFFLINE=1`). Re-run the script to "
          f"refresh numbers and figures.", "",
          "Third analysis step: after the source validation (`docs/indicators/validation/`) and the power spectra "
          "(`docs/indicators/spectra/`). The spectra say which cycles exist; this step measures them (amplitude, "
          "timing, uncertainty) with a harmonic regression, and then asks whether the annual means show a linear "
          "change. Everything marked **SYNTHETIC** is generated, not measured, and only checks the method.", ""]
    interp = out / "interpretation.md"
    if interp.exists():
        L += [interp.read_text(encoding="utf-8").strip(), ""]
    L += ["## Method", "",
          "- **Data**: the same trusted, QC'd daily series as the two earlier steps (validation loaders imported "
          "read-only): buoys EUXRo03 (2013-06 to 2023-10) and EUXRoOB01-03 (2024-04 to 2026-11), satellite and model "
          "at the buoy position over the buoy period. Chlorophyll is analysed in log10, so its weekly and monthly "
          "values are means of log10 (geometric means) and its amplitude is a factor: amplitude 0.2 means x1.6 above "
          "and /1.6 below the mean.",
          "- **Windows** (as agreed): annual cycle on monthly means over the last 20 years, seasonal on weekly means "
          "over the last 10 years. The cached records are shorter, so each window is the longest available and is "
          "stated in every table row: about 10 years at EUXRo03, 2.6 years at OB01-03. Satellite SST from 1982 or a "
          "longer model run would allow the full 20-year window; not downloaded (slow API).",
          "- **Aggregation**: calendar-month and calendar-week means of the daily values; a month needs at least 10 "
          "days, a week at least 4 (OURS). Each aggregate keeps n and SE = sd / sqrt(n); a WLS fit with weights "
          "1 / SE² is computed next to the OLS fit (`cycles.csv`: amplitude_wls, max_date_wls; `models.csv`: "
          "r2_adj_wls). The OLS fit is the one reported here.",
          "- **Periods from the PSD step** (`docs/indicators/spectra/peaks.csv`), per station / variable / source: "
          "real (non-SYNTHETIC) peaks with significant_95 true, from both the full and the anomaly spectrum, in the "
          "PSD's rank order (1 = strongest by power); kept only if fittable (at least 2 sampling steps: about 61 d "
          "for monthly, 14 d for weekly means; at most the record length); a peak closer in frequency than one "
          "spectral resolution step to an already chosen one is skipped; up to 3. The rows the PSD step adds with "
          "significant_95 false (nearest annual / semi-annual maximum) are not used.",
          "- **Fallback when a series' own spectrum gives fewer than 3** (OURS): the list is filled with significant "
          "seasonal-band peaks (>= 60 d) of the same variable from the other sources at the same station, then from "
          "the same source at the other stations, and the table says where each period comes from. Reason: the "
          "2.6-year buoy records give a full spectrum with one segment and 2 degrees of freedom, so even the obvious "
          "annual SST cycle of buoy OB01 is not significant in its own spectrum; without the fallback its fit would "
          "have no seasonal term. Short periods are never borrowed.",
          "- **Snapping**: a peak the PSD step labels annual or semi-annual is fitted at exactly 365.25 / k days "
          "when its frequency is within one resolution step of it: a 3-year segment only locates the annual peak to "
          "roughly 330-410 days, and fitting a 397-day sinusoid to 10 years of data would drift by months. The PSD "
          "period stays in `cycles.csv` (period_psd_d). The 2-10 day peaks of the anomaly spectra cannot be fitted on "
          "weekly or monthly means (the PSD step itself reads most of them as chance exceedances).",
          "- **Model**: y(t) = a0 + b t + sum_k [a_k cos(2 pi t / P_k) + b_k sin(2 pi t / P_k)], t in days since "
          "1 January of the first year. Amplitude A_k = sqrt(a_k² + b_k²); time of the maximum = atan2(b_k, a_k) "
          "P_k / 2 pi, shown as a calendar date. Standard errors of A and of the date by the delta method. A monthly "
          "or weekly mean shrinks a cycle by sinc(bin / P): 1.1 % for the annual cycle in monthly means, 4.5 % for the "
          "semi-annual, 11 % for a 97-day cycle; the amplitudes in the tables are corrected for it (raw values and "
          "the factor in `cycles.csv`), the curves in the figures are those of the means.",
          "- **Autocorrelation**: residuals of weekly (and often monthly) means are autocorrelated, so all standard "
          "errors, 95 % CIs and p-values use the Newey-West HAC covariance (Bartlett kernel; lag = the larger of "
          "floor(4 (n/100)^(2/9)) and the first lag where the residual autocorrelation falls below 0.1, at most n / 4, "
          "OURS: the plain rule gives 5 weeks while weekly residuals stay correlated for months); "
          "classic OLS values are in the CSV for comparison. A cycle's p-value is the joint Wald test of its "
          "cos and sin terms.",
          "- **Fit quality**: R², adjusted R², residual sd, AIC and BIC (Gaussian likelihood); nested models with "
          "0, 1, 2, 3 cycles (`nested.csv`): dAIC per added cycle (negative = better; below -2 is a clear gain), "
          "classic F-test and HAC Wald p. Residual checks: lag-1 autocorrelation, Durbin-Watson, Ljung-Box (10 lags) "
          "and effective n = n (1 - r1) / (1 + r1).",
          "- **Interannual trend**: annual means of the daily series, only for complete years: at least 80 % of days "
          "and every season with at least 50 % of its days (OURS); the current year 2026 is excluded. OLS of the "
          "annual means on year: slope per decade with 95 % CI (t distribution), p-value, R², n years. Error bars "
          "= 95 % CI of each annual mean from its day-to-day noise only (daily anomalies from a 31-day running mean, "
          "effective n from their autocorrelation); the spread of the points around the line is the year-to-year "
          "variability, which the OLS CI of the slope accounts for. With fewer than "
          "8 complete years the trend is reported as not meaningful, without a number. No Mann-Kendall and no other "
          "methods, by design.",
          "- **Figures**: top, the aggregated data (± SE) and the full fit; middle, one panel per cycle, folded on "
          "its period, with partial residuals (data minus all other terms); bottom, residuals over time and their "
          "autocorrelation (grey band = ± 1.96 / sqrt(n)). Okabe-Ito colours.", ""]

    L += ["## Method check on SYNTHETIC data", "",
          "The PSD step's SYNTHETIC 40-year daily SST-like series (`scripts/spectra/synthetic.py`: annual 8 °C with "
          "the maximum on day 220, semi-annual 1 °C, 6-year oscillation 0.4 °C, trend +0.4 °C/decade, AR(1) red noise "
          "rho 0.85, sd 0.7 °C), with the planted periods passed to the fit. `ok` = the planted value is inside the "
          "95 % CI. The same checks, plus gappy series, a 9-day cycle on daily data and a spurious period, run as "
          "unit tests in `tests/test_seasonal.py`.", "", _md(syn), ""]
    for fp, cap in synfigs:
        L += [f"![{cap}](figures/{fp.name})", "",
              "What: the fit recovers the planted amplitudes and dates within their confidence intervals. So what: "
              "the method is unbiased on a record like the real ones; the uncertainty on real data comes from the "
              "data, not the method.", ""]

    L += ["## Periods used (from peaks.csv)", "",
          f"`peaks.csv` has {len(peaks)} rows with columns `{', '.join(peaks.columns)}`: the format announced in "
          f"the task brief plus the PSD step's extra columns. An earlier version of the file (station, variable, "
          f"source, spectrum, method, period_d, cycle, psd_over_background, psd_over_95_level, dof, segments, "
          f"seg_days, data_note; no rank) is also accepted by `select_periods`. The buoy source is spelled `in situ` "
          f"in the file and read as `insitu`. The periods fitted per series, where each comes from and whether it "
          f"was snapped are in `cycles.csv` (period_psd_d, period_d, period_from, snapped).", ""]
    for var in ["sst", "chl", "sal", "o2"]:
        if var not in set(mod.variable):
            continue
        L += [f"## {TITLE[var]} ({UNIT[var]})", "", "### Seasonal cycles", "", _md(_fit_rows(var, cyc, mod, nest)), "",
              "### Interannual linear trend", "", _md(_trend_rows(var, trd)), ""]
        for s in summary:
            k = s["key"]
            if k["variable"] != var:
                continue
            show = k["station"] == "EUXRo03" or (k["station"] == "EUXRoOB01" and k["window"] == "weekly")
            if show:
                L += [f"![{k['station']} {var} {k['source']} {k['window']}](figures/{s['fig'].name})", "", s["text"], ""]
        others = [s for s in summary if s["key"]["variable"] == var and not (
            s["key"]["station"] == "EUXRo03" or (s["key"]["station"] == "EUXRoOB01" and s["key"]["window"] == "weekly"))]
        if others:
            L += ["Other figures: " + ", ".join(f"[{s['key']['station']} {s['key']['source']} {s['key']['window']}]"
                                                f"(figures/{s['fig'].name})" for s in others), ""]
            L += ["<details><summary>Plain-language sentences for these figures</summary>", ""]
            L += [f"- **{s['key']['station']} {s['key']['source']} {s['key']['window']}**: {s['text']}" for s in others]
            L += ["", "</details>", ""]
    L += ["## Files", "",
          "- `cycles.csv`: one row per fitted cycle (period from the PSD and used, amplitude, HAC and OLS SE, 95 % CI, "
          "time and date of the maximum with SE and CI, HAC and OLS p, WLS amplitude and date).",
          "- `models.csv`: one row per fit (R², adj. R², residual sd, AIC, BIC, trend term, residual checks, "
          "WLS adj. R²).",
          "- `nested.csv`: models with 0..K cycles per fit (R², AIC, BIC, dAIC, dBIC, F, p_F, p_hac).",
          "- `trends.csv`, `annual_means.csv`: interannual trend and the annual means with completeness and reason.",
          "- `synthetic_check.csv`: the method check above.",
          "- Code: `scripts/seasonal/harmonic.py` (aggregate, fit_harmonics, compare_nested, select_periods), "
          "`scripts/seasonal/trend.py` (annual_means, linear_trend), `scripts/seasonal/run_seasonal.py` (this "
          "report). The functions take a pandas Series and a list of periods and return a dict / DataFrame, ready to "
          "move into a marinekit analysis package for a Research page.", ""]
    p = out / "README.md"
    p.write_text("\n".join(L), encoding="utf-8")
    return p

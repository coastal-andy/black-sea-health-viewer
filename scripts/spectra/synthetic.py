"""SYNTHETIC test series for the power-spectrum step (no download, no network).

Two series stand in for data that are not downloaded yet:

  * synthetic_long_daily():  about 40 years of daily values, like satellite SST from 1982. Planted: linear trend,
    annual and semi-annual cycles, a multi-year oscillation (6 years) and AR(1) red noise. Shows the long-period end
    of the spectrum that the 2.6- and 10-year real records cannot reach.
  * synthetic_hourly():      about 1 year of hourly values, like raw buoy records. Planted: diurnal cycle (24 h),
    inertial oscillation at 44 deg N (12 h / sin(44 deg) = 17.27 h), small semi-diurnal M2 tide (12.42 h), synoptic
    red noise (3-day memory), white sensor noise, and data gaps. Shows the sub-daily end of the spectrum.

Both return the same shape as marinekit.datahub.get_series(): a DataFrame with a DatetimeIndex named "time", one
column named after the variable, and attrs (variable, lat, lon, source_id, label, origin, trust, unit, ...). Every
label says SYNTHETIC. To use a real series later, replace the call by get_series(...) with the same variable name.

The planted values are in attrs["planted"], so tests and the report can check what the spectrum recovers.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

INERTIAL_H = 12.0 / np.sin(np.deg2rad(44.0))     # 17.27 h at 44 deg N (half a pendulum day)
M2_H = 12.4206                                    # principal lunar semi-diurnal tide


def _ar1(n: int, rho: float, sigma: float, rng: np.random.Generator) -> np.ndarray:
    """AR(1) noise with lag-1 autocorrelation rho and stationary standard deviation sigma."""
    e = rng.normal(0.0, sigma * np.sqrt(1.0 - rho ** 2), n)
    x = np.empty(n)
    x[0] = rng.normal(0.0, sigma)
    for i in range(1, n):
        x[i] = rho * x[i - 1] + e[i]
    return x


def _attrs(variable: str, unit: str, label: str, planted: dict, lat: float, lon: float) -> dict:
    return dict(variable=variable, lat=lat, lon=lon, requested_source="synthetic", source_id="synthetic",
                label=f"SYNTHETIC: {label}", origin="synthetic", evidence="synthetic", trust="synthetic", unit=unit,
                datasets=[], distance_km=0.0, notes=["SYNTHETIC series generated by scripts/spectra/synthetic.py"],
                planted=planted)


def synthetic_long_daily(start: str = "1982-01-01", end: str = "2021-12-31", seed: int = 1982,
                         lat: float = 43.98, lon: float = 29.936) -> pd.DataFrame:
    """SYNTHETIC daily SST-like series (deg C), gap-free, about 40 years."""
    rng = np.random.default_rng(seed)
    idx = pd.date_range(start, end, freq="D", name="time")
    t = (idx - idx[0]).days.to_numpy(float)                       # days since start
    doy = idx.day_of_year.to_numpy(float)
    p = dict(mean=14.5, trend_per_year=0.04, annual_amp=8.0, annual_period_d=365.25, annual_peak_doy=220,
             semiannual_amp=1.0, semiannual_period_d=365.25 / 2, multiyear_amp=0.4, multiyear_period_d=6 * 365.25,
             ar1_rho=0.85, ar1_sigma=0.7)
    w = 2 * np.pi
    y = (p["mean"] + p["trend_per_year"] * t / 365.25
         + p["annual_amp"] * np.cos(w * (doy - p["annual_peak_doy"]) / p["annual_period_d"])
         + p["semiannual_amp"] * np.cos(w * (doy - 40) / p["semiannual_period_d"])
         + p["multiyear_amp"] * np.sin(w * t / p["multiyear_period_d"])
         + _ar1(len(t), p["ar1_rho"], p["ar1_sigma"], rng))
    df = pd.DataFrame({"sst": y}, index=idx)
    df.attrs = _attrs("sst", "°C", "40-year daily SST-like series (trend, annual, semi-annual, 6-year, red noise)",
                      p, lat, lon)
    return df


def synthetic_hourly(start: str = "2025-01-01", days: int = 365, seed: int = 44, gaps: bool = True,
                     lat: float = 44.0, lon: float = 29.9) -> pd.DataFrame:
    """SYNTHETIC hourly SST-like series (deg C), about 1 year, with gaps (NaN rows removed when gaps=True)."""
    rng = np.random.default_rng(seed)
    idx = pd.date_range(start, periods=days * 24, freq="h", name="time")
    th = np.arange(len(idx), dtype=float)                          # hours since start
    p = dict(mean=15.0, annual_amp=7.0, diurnal_amp=0.30, diurnal_period_h=24.0, inertial_amp=0.12,
             inertial_period_h=float(INERTIAL_H), m2_amp=0.04, m2_period_h=M2_H, synoptic_rho_h=float(np.exp(-1 / 72)),
             synoptic_sigma=0.6, white_sigma=0.05, gap_share_target=0.15 if gaps else 0.0)
    w = 2 * np.pi
    y = (p["mean"] - p["annual_amp"] * np.cos(w * (th / 24 - 30) / 365.25)
         + p["diurnal_amp"] * np.cos(w * (th - 15) / p["diurnal_period_h"])   # warmest 15:00
         + p["inertial_amp"] * np.cos(w * th / p["inertial_period_h"])
         + p["m2_amp"] * np.cos(w * th / p["m2_period_h"])
         + _ar1(len(th), p["synoptic_rho_h"], p["synoptic_sigma"], rng)
         + rng.normal(0, p["white_sigma"], len(th)))
    df = pd.DataFrame({"sst": y}, index=idx)
    if gaps:
        keep = np.ones(len(th), bool)
        # outages of 1 to 10 days, then isolated dropouts, until about 15 % is missing
        while (~keep).mean() < 0.12:
            a = rng.integers(0, len(th))
            keep[a:a + rng.integers(24, 240)] = False
        keep &= rng.random(len(th)) > 0.03
        df = df[keep]
        p["gap_share"] = round(1 - keep.mean(), 3)
    df.attrs = _attrs("sst", "°C", "1-year hourly SST-like series (diurnal, inertial 17.3 h, M2 tide, synoptic noise"
                      + (", gaps)" if gaps else ", gap-free)"), p, lat, lon)
    return df

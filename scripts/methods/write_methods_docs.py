"""Write docs/indicators/methods/MEASUREMENT_NEEDS.md and measurement_needs.csv from marinekit.methods.

Offline, reads committed result files only. Run from the repo root:
    .venv/Scripts/python.exe scripts/methods/write_methods_docs.py
The markdown is a snapshot for review and the pitch; the viewer calls marinekit.methods directly.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from marinekit import methods as M  # noqa: E402

OUT = ROOT / "docs" / "indicators" / "methods"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    df = M.measurement_needs()
    df.to_csv(OUT / "measurement_needs.csv", index=False)

    lines = [
        "# New measurement needs and uncertainty by user level",
        "",
        f"Generated by `scripts/methods/write_methods_docs.py` from `marinekit.methods` (results of {M.RUN_DATE}). "
        "Do not edit by hand: change the module and re-run. All numbers indicative.",
        "",
        "## 1. New measurement needs",
        "",
        "Five yes/no criteria per need, counted (no weights, no composite index; criteria and thresholds OURS):",
        "",
        "- **D, sources disagree**: |bias| larger than the variable's typical error, or R2 of the anomalies "
        f"below {M.DISAGREE_R2_ANOM}; nutrients: Spearman below {M.DISAGREE_SPEARMAN}.",
        f"- **N, no trusted in-situ sensor** reporting there (trust good or usable, data within {M.REPORTING_DAYS} "
        "days).",
        "- **S, a sensor exists but is not trusted** (flag in `marinekit.datahub`): usually the cheapest fix.",
        f"- **T, gap in time**: no trusted source passes the trend gate ({M.TREND_MIN_YEARS} complete years), or the "
        "in-situ record has ended, or there is none.",
        "- **P, decision at stake**: an OFFICIAL-RO or OFFICIAL-EU threshold depends on the variable.",
        "",
        "Order: more reasons first; ties go to needs behind an official threshold, then to the cheaper action.",
        "",
        "| Rank | What to measure | Where | Reasons (of 5) | How | Cost | Who |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in df.itertuples():
        codes = "".join(c for c, k in zip("DNSTP", M.CRITERIA) if getattr(r, k)) or "-"
        lines.append(f"| {r.rank} | {r.what} | {r.where} | {r.n_reasons} ({codes}) | {r.how} | {r.cost} | {r.who} |")
    lines += ["", "### Why and evidence", ""]
    for r in df.itertuples():
        lines.append(f"**{r.rank}. {r.what}** ({r.need_id}). {r.why}")
        lines.append("")
        for part in r.evidence.split(" | "):
            lines.append(f"- {part}")
        if r.hand_set:
            lines.append(f"- set by hand (no matched data to compute it): {r.hand_set}")
        lines.append("")

    lines += ["## 2. Uncertainty explained by user level", ""]
    for role in M.PROFILES:
        lines += [f"### Introduction, {role}", "", M.uncertainty_primer(role), ""]
    for v in M.uncertainty_variables():
        lines += [f"### {v}", ""]
        for prof in ["public", "student", "stakeholder", *[f"stakeholder:{s}" for s in M.SECTORS], "researcher"]:
            t = M.uncertainty_text(v, prof)
            if prof.startswith("stakeholder:") and t == M.uncertainty_text(v, "stakeholder"):
                continue
            lines += [f"**{prof}**", "", t, ""]
    (OUT / "MEASUREMENT_NEEDS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT / 'MEASUREMENT_NEEDS.md'} and measurement_needs.csv ({len(df)} needs)")


if __name__ == "__main__":
    main()
